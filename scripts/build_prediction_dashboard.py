"""Build a local HTML dashboard that overlays predictions and observed prices."""

from __future__ import annotations

import argparse
import webbrowser
from pathlib import Path

from src.visualization import DashboardConfig, save_prediction_dashboard


def parse_args() -> argparse.Namespace:
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument(
        "--scored-path",
        default=Path("Data/processed/scored_options.csv"),
        type=Path,
        help="Scored options CSV generated by score_option_dataset.py.",
    )
    parser.add_argument(
        "--option-dataset-path",
        default=Path("Data/processed/option_training_dataset.csv"),
        type=Path,
        help="Canonical option dataset CSV with strike, expiration and last price metadata.",
    )
    parser.add_argument(
        "--market-history-path",
        default=Path("Data/final/master_dataset_2010_present_long.csv"),
        type=Path,
        help="Market history CSV used for the underlying historical chart.",
    )
    parser.add_argument(
        "--history-days",
        default=252,
        type=int,
        help="Number of latest market rows to show in the historical chart.",
    )
    parser.add_argument(
        "--output",
        default=Path("reports/prediction_dashboard.html"),
        type=Path,
        help="Output HTML dashboard path.",
    )
    parser.add_argument(
        "--title",
        default="Proyecto TAM - Prediction Dashboard",
        help="Dashboard title.",
    )
    parser.add_argument(
        "--open",
        action="store_true",
        help="Open the generated HTML dashboard in the default browser.",
    )
    return parser.parse_args()


def main() -> None:
    args = parse_args()
    output_path = save_prediction_dashboard(
        DashboardConfig(
            scored_path=args.scored_path,
            option_dataset_path=args.option_dataset_path,
            market_history_path=args.market_history_path,
            output_path=args.output,
            title=args.title,
            history_days=args.history_days,
        )
    )
    print(f"Saved prediction dashboard to {output_path}")
    if args.open:
        webbrowser.open(output_path.resolve().as_uri())


if __name__ == "__main__":
    main()
